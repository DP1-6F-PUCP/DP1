import assert from 'node:assert/strict';
import { QueryClient } from '@tanstack/react-query';
import { iniciarEjecucion, cerrarEjecucion } from '../src/services/scenarioLifecycle';
import { escenariosApi } from '../src/services/escenariosApi';
import { estadoOperacionApi } from '../src/services/estadoOperacionApi';
import { configuracionApi } from '../src/services/configuracionApi';
import { useScenarioStore } from '../src/store/scenarioStore';
import { useMapStore } from '../src/store/mapStore';
import { simulationEngine } from '../src/engine/simulationEngine';
import fixture from './fixtures/enero-ruta.json';
const client=new QueryClient({defaultOptions:{queries:{retry:false,gcTime:0}}});
const old={idEjecucion:'old',tipoEscenario:'CINCO_DIAS',estado:'FINALIZADA',fechaInicio:'2026-10-28T00:00:00Z',fechaInicioSimulada:'2026-01-01T00:00:00Z',sa:5/60,k:150} as const;
const fresh={...old,idEjecucion:'new',estado:'EN_CURSO' as const,fechaInicioSimulada:'2026-02-01T00:00:00Z'};
const state={...fixture.estado,idEjecucion:'new',marcaTiempoActual:'2026-02-01T00:00:00'} as any;
useScenarioStore.getState().setEjecucion(old);
useMapStore.setState({selectedVehicleId:'TA02',selectedOrderId:'old-order'});
client.setQueryData(['estado-operacion','old'],fixture.estado);
client.setQueryData(['pedidos','old'],[{idPedido:'old-order'}]);
client.setQueryData(['escenario-activa'],{...old,estado:'EN_CURSO'});
let resolveOld:(v:any)=>void=()=>{};
const oldQuery=client.fetchQuery({queryKey:['estado-operacion','late-old'],queryFn:()=>new Promise(r=>resolveOld=r)}).catch(()=>{});
let resolveFresh:(v:any)=>void=()=>{};
estadoOperacionApi.getEstado=()=>new Promise(r=>resolveFresh=r);
estadoOperacionApi.getPedidos=async()=>[];
configuracionApi.getConfiguracion=async()=>fixture.config as any;
escenariosApi.iniciarEscenario=async()=>fresh;
const starting=iniciarEjecucion(client,{tipo:'CINCO_DIAS',fechaInicioSimulada:fresh.fechaInicioSimulada});
assert.equal(useScenarioStore.getState().transicion,'iniciando');
while(useScenarioStore.getState().transicion!=='preparando') await new Promise(r=>setTimeout(r,0));
assert.equal(useScenarioStore.getState().ejecucion?.idEjecucion,'old','No se expone el escenario nuevo antes de tener datos');
assert.equal(useMapStore.getState().selectedVehicleId,null);
assert.equal(simulationEngine.getSnapshotNow().nowSimMs,Date.parse(fresh.fechaInicioSimulada));
assert.equal(useScenarioStore.getState().playbackStartedAtMs,null);
let batch=0;
estadoOperacionApi.getEstado=async()=>({...state,marcaTiempoActual:
  ['2026-02-01T00:12:30','2026-02-01T00:25:00','2026-02-01T00:37:30'][Math.min(batch++,2)]});
escenariosApi.consultarEscenario=async()=>fresh;
resolveFresh(state);
await new Promise(r=>setTimeout(r,20));
assert.equal(useScenarioStore.getState().transicion,'preparando','Recibir el estado inicial no basta para retirar el cargador');
assert.equal(useScenarioStore.getState().playbackStartedAtMs,null,'La preparación no cuenta como tiempo transcurrido');
await starting;
resolveOld(fixture.estado);await oldQuery;
assert.equal(useScenarioStore.getState().transicion,null);
assert.equal(useScenarioStore.getState().ejecucion?.idEjecucion,'new');
assert.equal(client.getQueryData(['estado-operacion','old']),undefined);
assert.equal(client.getQueryData(['estado-operacion','late-old']),undefined);
assert.equal((client.getQueryData(['estado-operacion','new']) as any).idEjecucion,'new');
assert(useScenarioStore.getState().playbackStartedAtMs!>0);
assert.equal(simulationEngine.getSnapshotNow().buffering,false);
let resolveClose:()=>void=()=>{};
escenariosApi.detener=()=>new Promise<void>(r=>resolveClose=r);
const closing=cerrarEjecucion(client,'new');
while(useScenarioStore.getState().transicion!=='cerrando') await new Promise(r=>setTimeout(r,0));
await new Promise(r=>setTimeout(r,0));
assert.equal(useScenarioStore.getState().ejecucion?.estado,'EN_CURSO');
resolveClose();await closing;
assert.equal(useScenarioStore.getState().ejecucion?.estado,'FINALIZADA');
assert.equal(client.getQueryData(['escenario-activa']),null);
assert.equal(client.getQueryData(['pedidos','new']),undefined);
assert(useScenarioStore.getState().playbackStartedAtMs!>0,'Se conserva el inicio visible para calcular la duración del reporte');
escenariosApi.iniciarEscenario=async()=>{throw new Error('Sin conexión');};
await assert.rejects(iniciarEjecucion(client,{tipo:'CINCO_DIAS'}),/Sin conexión/);
assert.equal(useScenarioStore.getState().transicion,null,'Un error no deja la pantalla bloqueada');
const early={...fresh,idEjecucion:'early',estado:'DETENIDA_POR_INCUMPLIMIENTO' as const};
escenariosApi.iniciarEscenario=async()=>({...early,estado:'EN_CURSO'});
escenariosApi.consultarEscenario=async()=>early;
estadoOperacionApi.getEstado=async()=>({...state,idEjecucion:'early'});
const finished=await iniciarEjecucion(client,{tipo:'CINCO_DIAS',fechaInicioSimulada:early.fechaInicioSimulada});
assert.equal(finished.estado,'DETENIDA_POR_INCUMPLIMIENTO','Un colapso durante la carga debe abrir el reporte, no descartarse como error de arranque');
assert.equal(useScenarioStore.getState().playbackStartedAtMs,null);
assert.equal(useScenarioStore.getState().transicion,null);
client.clear();
console.log('OK: carga hasta recibir datos, aislamiento de consultas tardías, cierre confirmado y recuperación ante errores.');
