import assert from 'node:assert/strict';
import { SimulationEngine } from '../src/engine/simulationEngine';
import { parseBackendSimulatedTime as time } from '../src/utils/backendTime';
const engine=new SimulationEngine();let real=100000;
Object.defineProperty(performance,'now',{value:()=>real,configurable:true});
const frame=(id:string,mark:string)=>({vehicles:[],routes:[],orders:[],warehouses:[],blockedStreets:[],estadoRaw:{idEjecucion:id,marcaTiempoActual:mark,rutas:[],vehiculos:[],almacenes:[],bloqueos:[],eventos:[],metricas:{}} as any});
const ingest=(id:string,sourceId:string,mark:string)=>engine.ingest({vehicles:[],routes:[],frame:frame(sourceId,mark),idEjecucion:id,sa:5/60,marcaTiempoActual:mark,k:150,avanzando:true});
ingest('old','old','2026-11-01T18:00:00');
const start=time('2026-01-01T00:00:00');
engine.beginExecution('new',start);
assert.equal(engine.getSnapshotNow().nowSimMs,start);
ingest('new','old','2026-11-01T18:12:30');
assert.equal(engine.getSnapshotNow().nowSimMs,start,'Un paquete del escenario anterior no adelanta el reloj');
ingest('new','new','2026-01-01T00:12:30');
assert.equal(engine.getSnapshotNow().nowSimMs,start,'El primer lote adelantado no cambia la hora inicial elegida');
real+=5000;ingest('new','new','2026-01-01T00:25:00');
assert.equal(engine.getSnapshotNow().nowSimMs,start);
real+=5000;ingest('new','new','2026-01-01T00:37:30');
real+=3000;engine.advance();
assert(engine.getSnapshotNow().nowSimMs!>=start && engine.getSnapshotNow().nowSimMs!<time('2026-01-01T01:00:00'));
const last=engine.getSnapshotNow().nowSimMs;
ingest('new','old','2026-11-01T20:00:00');
assert.equal(engine.getSnapshotNow().nowSimMs,last);
const second=time('2026-02-01T07:00:00');
engine.beginExecution('second',second);
ingest('second','second','2026-02-01T07:12:30');
assert.equal(engine.getSnapshotNow().nowSimMs,second,'Una segunda ejecución vuelve a comenzar en su propia hora');
console.log('OK: arranque exacto a las 00:00, primer lote adelantado y mensajes tardíos de otra ejecución.');
